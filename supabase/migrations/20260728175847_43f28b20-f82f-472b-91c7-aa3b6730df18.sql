-- Process events function
CREATE OR REPLACE FUNCTION public.process_mes_event(p_event_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_event mes_events%ROWTYPE;
BEGIN
    SELECT * INTO v_event FROM mes_events WHERE id = p_event_id;
    
    IF v_event.status = 'processed' THEN
        RETURN;
    END IF;

    -- Actual processing logic based on event_type
    CASE v_event.event_type
        WHEN 'production_started' THEN
            -- Implement start logic if needed
            NULL;
        WHEN 'production_quantity_reported' THEN
            -- Map to op_apontamentos
            INSERT INTO op_apontamentos (
                op_id, 
                funcionario_id, 
                maquina_id, 
                inicio, 
                quantidade_produzida, 
                idempotency_key
            ) VALUES (
                v_event.op_id,
                v_event.operator_id,
                v_event.machine_id,
                v_event.occurred_at,
                (v_event.payload->>'quantity')::numeric,
                v_event.event_id
            );
        WHEN 'production_loss_reported' THEN
             -- Map to op_apontamentos (as refugo)
            INSERT INTO op_apontamentos (
                op_id, 
                funcionario_id, 
                maquina_id, 
                inicio, 
                quantidade_refugo, 
                motivo_refugo,
                idempotency_key
            ) VALUES (
                v_event.op_id,
                v_event.operator_id,
                v_event.machine_id,
                v_event.occurred_at,
                (v_event.payload->>'quantity')::numeric,
                (v_event.payload->>'reason')::text,
                v_event.event_id
            );
        ELSE
            NULL;
    END CASE;

    UPDATE mes_events 
    SET status = 'processed', processed_at = now() 
    WHERE id = p_event_id;
END;
$$;

-- 2. mes_agents table
CREATE TABLE IF NOT EXISTS public.mes_agents (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name text NOT NULL,
    activation_code text UNIQUE NOT NULL,
    unit text,
    equipment_id text,
    status public.mes_agent_status DEFAULT 'pending',
    token_hash text, -- Securely hashed token
    last_communication timestamptz,
    version text,
    created_at timestamptz DEFAULT now(),
    updated_at timestamptz DEFAULT now()
);

-- 3. mes_events table
CREATE TABLE IF NOT EXISTS public.mes_events (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    event_id uuid UNIQUE NOT NULL, -- The UUID generated by the agent for idempotency
    agent_id uuid REFERENCES public.mes_agents(id) NOT NULL,
    event_type public.mes_event_type NOT NULL,
    machine_id uuid REFERENCES public.maquinas(id),
    op_id uuid REFERENCES public.ordens_producao(id),
    operator_id uuid REFERENCES public.funcionarios(id),
    occurred_at timestamptz NOT NULL,
    payload jsonb DEFAULT '{}'::jsonb,
    processed_at timestamptz,
    status text DEFAULT 'pending' CHECK (status IN ('pending', 'processed', 'error', 'ignored')),
    error_message text,
    created_at timestamptz DEFAULT now()
);

-- 4. mes_heartbeats table
CREATE TABLE IF NOT EXISTS public.mes_heartbeats (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    agent_id uuid REFERENCES public.mes_agents(id) NOT NULL,
    version text,
    status text,
    local_time timestamptz,
    pending_events_count integer DEFAULT 0,
    last_sync timestamptz,
    created_at timestamptz DEFAULT now()
);

